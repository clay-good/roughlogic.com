// Emits constant-notes.js: the tiles whose "Note" output is the SAME text no
// matter what the reader types.
//
// A note that never changes is not part of the answer -- it is reference
// prose that happens to be returned alongside it. Rendered in the answer
// region it becomes a second disclosure on the page, a median 565 characters
// of explanation sitting between the number the reader came for and the one
// block that holds the formula and the sources. app.js moves the tiles listed
// here into that block instead, so the answer region holds only the answer.
//
// The note itself is untouched: `run_calculator` still returns it, because an
// agent reading a result has no page to open and the note is the only prose it
// gets. This is a placement decision for the human surface only.
//
// Constancy is MEASURED, not declared: each compute runs twice, once with its
// worked-example inputs and once with every number perturbed. A note that
// comes back byte-identical from two different answers cannot be commenting on
// either of them.
//
// Usage: node scripts/extract-constant-notes.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { COMPUTE_MAP, importCalc } from "../test/fixtures/compute-map.js";
import { TOOLS } from "../tools-data.js";
const OUT = new URL("../constant-notes.js", import.meta.url);
const EXAMPLES = new URL("../test/fixtures/worked-examples.json", import.meta.url);

// Same shape a renderer reads: `note` when the compute returns one string,
// `notes` when it returns the lines a renderer joins.
function noteOf(result) {
  if (!result || typeof result !== "object") return null;
  if (typeof result.note === "string") return result.note;
  if (Array.isArray(result.notes) && result.notes.every((n) => typeof n === "string")) return result.notes.join(" ");
  return null;
}

// Perturb every number so a note that reads the answer has to change. The
// multiplier is deliberately awkward (1.37x + 0.11) rather than a round
// factor: a tile that snaps its inputs to a standard size would return the
// same note for 10 and 20, but not for 10 and 13.81.
function perturb(inputs) {
  const out = {};
  for (const [k, v] of Object.entries(inputs || {})) {
    if (typeof v === "number") out[k] = v * 1.37 + 0.11;
    else if (Array.isArray(v)) out[k] = v.map((n) => (typeof n === "number" ? n * 1.37 + 0.11 : n));
    else out[k] = v;
  }
  return out;
}

async function collect() {
  const rows = JSON.parse(readFileSync(EXAMPLES, "utf8")).rows;
  const inputsByTile = new Map();
  for (const r of rows) if (!inputsByTile.has(r.tile_id)) inputsByTile.set(r.tile_id, r.inputs);

  const ids = [];
  for (const [id, entry] of Object.entries(COMPUTE_MAP)) {
    const inputs = inputsByTile.get(id);
    if (!inputs) continue;
    let fn;
    try { fn = (await importCalc(entry.module))[entry.fn]; } catch { continue; }
    if (typeof fn !== "function") continue;
    let a, b;
    // A compute that throws on the perturbed inputs tells us nothing about
    // constancy, so it stays where it is.
    try { a = fn(inputs); b = fn(perturb(inputs)); } catch { continue; }
    const na = noteOf(a);
    const nb = noteOf(b);
    // An error branch returns no note; two errors would compare equal and
    // wrongly look constant.
    if (a && a.error) continue;
    if (b && b.error) continue;
    if (typeof na !== "string" || !na.trim()) continue;
    if (na !== nb) continue;
    ids.push(id);
  }
  return ids.sort();
}

// One bit per tile, in TOOLS order, base64'd.
//
// The obvious encoding -- 976 quoted tile ids -- is 8.7 KB gzipped against this
// module's 6 KB budget, and the ids are pure redundancy: every one of them is
// already in tools-data.js, which any tile page has loaded before this module
// is reached. So ship the ANSWER (yes/no per tile) rather than the questions:
// 1,709 bits is 214 bytes, ~300 after base64, and the ids come from TOOLS.
//
// This couples the file to the ORDER of TOOLS. That coupling is safe because
// it is gated, not remembered: `--check` regenerates and byte-compares, so
// adding or reordering a tile fails lint until this file is regenerated. It
// can be stale in the working tree; it cannot ship stale.
function render(ids) {
  const set = new Set(ids);
  const bytes = new Uint8Array(Math.ceil(TOOLS.length / 8));
  TOOLS.forEach((t, i) => { if (set.has(t.id)) bytes[i >> 3] |= 1 << (i & 7); });
  const b64 = Buffer.from(bytes).toString("base64");
  return [
    "// GENERATED by scripts/extract-constant-notes.mjs. Do not hand-edit.",
    "// Tiles whose \"Note\" output is identical for every set of inputs -- reference",
    "// prose, not an observation about the answer. app.js moves these out of the",
    "// answer region and into the one collapsed Details block, so a tile page shows",
    "// the number first and keeps its explanation in the single place it belongs.",
    "// The compute still returns the note; only where it is PRINTED changes.",
    "//",
    `// ${ids.length} of ${TOOLS.length} tiles, one bit each in TOOLS order (see the`,
    "// generator for why this is a bitmap and not a list of ids).",
    'import { TOOLS } from "./tools-data.js";',
    "",
    `const BITS = "${b64}";`,
    "",
    "const bytes = Uint8Array.from(atob(BITS), (c) => c.charCodeAt(0));",
    "export const CONSTANT_NOTE_TILES = new Set(",
    "  TOOLS.filter((t, i) => (bytes[i >> 3] >> (i & 7)) & 1).map((t) => t.id)",
    ");",
    "",
  ].join("\n");
}

const ids = await collect();
const next = render(ids);
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing counts as drift */ }
  if (current !== next) {
    console.error("constant-notes.js is out of date. Run: node scripts/extract-constant-notes.mjs");
    process.exit(1);
  }
  console.log(`✓ constant-notes.js is in sync (${ids.length} tiles).`);
} else {
  writeFileSync(OUT, next);
  console.log(`extract-constant-notes: wrote ${ids.length} tiles to constant-notes.js`);
}

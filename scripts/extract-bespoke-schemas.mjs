// Parse a literal [{ value: "..", label: ".." }, ...] options array from source.
function parseOptions(src) {
  const opts = [];
  const re = /\{\s*value:\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')\s*,\s*label:\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')/g;
  let m;
  while ((m = re.exec(src))) {
    opts.push({ value: JSON.parse(m[1].replace(/'/g, '"')), label: JSON.parse(m[2].replace(/'/g, '"')) });
  }
  return opts;
}

// Globals a pure options-builder never needs. Shadowed as `undefined` inside the
// evaluator so an expression that reaches for the DOM, the network, or the
// filesystem throws instead of running.
const DENIED_GLOBALS = [
  "document", "window", "globalThis", "self", "fetch", "process", "require",
  "Function", "localStorage", "sessionStorage", "XMLHttpRequest",
  "navigator", "location", "setTimeout", "setInterval",
];

// `eval` and `arguments` cannot be shadowed by a parameter in strict mode, so
// an expression naming either is rejected outright instead.
const DENIED_TOKENS = /\b(eval|arguments)\b/;

// Evaluate a makeSelect options expression against its own module's exports.
//
// Roughly a third of the bespoke renderers build their dropdown from a
// module-level table -- `Object.keys(SPRINKLER_HAZARD_MIN_DENSITY).map(...)`,
// `[{value:"",label:"(none)"}].concat(...)`. Scraping those with a regex either
// finds nothing or, worse, finds only the literal head and reports a truncated
// enum (inventory-turnover advertised `[""]` while the page offered nine
// industries). Evaluating the expression with the module namespace bound gives
// the exact values the browser renders.
//
// Safety: the only bindings are the module's own exports plus a few pure
// builtins. Every other identifier -- a module-local helper, a DOM global -- is
// unbound and throws ReferenceError, so the field degrades to "dynamic, no
// enum" rather than to a guess.
function evalOptions(expr, ns) {
  if (DENIED_TOKENS.test(expr)) return null;
  const names = [];
  const values = [];
  for (const [k, v] of Object.entries(ns)) {
    if (!/^[A-Za-z_$][\w$]*$/.test(k)) continue;
    names.push(k); values.push(v);
  }
  for (const g of DENIED_GLOBALS) {
    if (names.includes(g)) continue;
    names.push(g); values.push(undefined);
  }
  let out;
  try {
    out = new Function(...names, `"use strict"; return (${expr});`)(...values);
  } catch { return null; }
  if (!Array.isArray(out) || out.length === 0) return null;
  const opts = [];
  for (const o of out) {
    if (!o || typeof o !== "object") return null;
    if (typeof o.value !== "string" && typeof o.value !== "number") return null;
    if (typeof o.label !== "string" && typeof o.label !== "number") return null;
    opts.push({ value: String(o.value), label: String(o.label) });
  }
  return opts;
}

// Map each compute RESULT key to the caption of the output line that displays
// it. Renderers declare a line as `const oG = makeOutputLine(region, "Total
// gpm", "sd-out-g")` and then fill it with `oG.textContent = fmt(r.total_gpm,
// 1) + " gpm"`. A line that shows exactly one result key names that key; a line
// that mixes two ("7.45 V (3.1%)") names neither, and is skipped rather than
// attributed to whichever came first. A caption two keys share is dropped for
// the same reason the input pass drops one.
// A module may import the shared factories under its own names --
// `import { makeOutputLine as _moG, fmt as _fmtG }` -- and twelve of them do.
// Anchoring on the literal `makeOutputLine` therefore read no output lines at
// all for those renderers, so 73 tiles named none of their answers even though
// their captions are right there in the source. (The same shape once cost the
// INPUT side 47 pages; there it was a prefix, `_v26makeNumber`, which a `\w*`
// still matched. A rename to `_v26makeOut` it cannot.)
//
// The renames only ever appear in an import clause, so scanning the module text
// for them is exact.
function factoryAliases(src) {
  const of = (name) => {
    const out = new Set([name]);
    for (const m of src.matchAll(new RegExp("\\b" + name + "\\s+as\\s+([A-Za-z_$][\\w$]*)", "g"))) out.add(m[1]);
    return [...out];
  };
  const alt = (names) => names.map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
  return {
    outLine: alt(of("makeOutputLine")),
    fmt: alt(of("fmt")),
    number: alt(of("makeNumber")),
    select: alt(of("makeSelect")),
    // The loose input pass models the text/row factories too.
    anyInput: alt([...of("makeNumber"), ...of("makeSelect"), ...of("makeText"),
                   ...of("makeTextarea"), ...of("makeRowField")]),
  };
}

const DEFAULT_ALIASES = {
  outLine: "makeOutputLine", fmt: "fmt", number: "makeNumber", select: "makeSelect",
  anyInput: "make(?:Number|Select|Text|Textarea|RowField)",
};

// Which variable a renderer holds its compute result in. The reads below were
// anchored on a literal `r.`, but plenty of renderers call it something else --
// `res` in twenty-one of the tiles that named no answers, `x` in `overtime`,
// whose four captions ("Regular pay", "Overtime pay", ...) sat one character
// away from being read.
//
// Only bindings that come from the SAME compute function are accepted. A
// renderer holding two different result objects could have a key that means one
// thing in each, and a caption attached to the wrong one is worse than none.
function resultVars(body) {
  const byFn = new Map();
  for (const m of body.matchAll(/\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*([\w$]*compute[A-Za-z0-9_$]*)\s*\(/g)) {
    if (!byFn.has(m[2])) byFn.set(m[2], new Set());
    byFn.get(m[2]).add(m[1]);
  }
  if (byFn.size !== 1) return ["r"];
  const names = new Set([...byFn.values()][0]);
  names.add("r");
  return [...names];
}

// `(?:r|res)\.` -- the result reads, for whichever names this renderer uses.
const resultRefRe = (vars, flags) =>
  new RegExp("\\b(?:" + vars.map((v) => v.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")\\.([A-Za-z_$][\\w$]*)", flags);

function parseOutputLabels(body, aliases = DEFAULT_ALIASES) {
  const REF_RE = resultRefRe(resultVars(body), "g");
  const lines = new Map();
  const LINE_RE = new RegExp("\\b([A-Za-z_$][\\w$]*)\\s*=\\s*(?:\\w*(?:" + aliases.outLine + "))\\(\\s*[A-Za-z_$][\\w$]*\\s*,\\s*(\"(?:[^\"\\\\]|\\\\.)*\")", "g");
  for (const m of body.matchAll(LINE_RE)) {
    lines.set(m[1], JSON.parse(m[2]));
  }
  if (lines.size === 0) return {};
  const map = {};
  const claimed = new Set();
  for (const m of body.matchAll(/([A-Za-z_$][\w$]*)\.textContent\s*=\s*([^;]*)/g)) {
    const label = lines.get(m[1]);
    if (label === undefined) continue;
    const refs = [...new Set([...m[2].matchAll(REF_RE)].map((x) => x[1]))];
    if (refs.length === 0) continue;
    // A line that shows more than one result ("300 gpm @ 0.2 gpm/ft^2") is
    // captioned for the value it leads with -- "Total gpm" names total_gpm --
    // so the first key wins and the rest of that line stays keyed. Except when
    // the caption itself is a list ("XL / XC", "Angles (A / B / C)"): that
    // names the whole line rather than its first value, and against one number
    // it reads wrong. Those stay keyed.
    if (refs.length > 1 && label.includes("/")) continue;
    const key = refs[0];
    // `oX.textContent = r.error` is the failure branch of a line whose caption
    // belongs to the value it shows when things go right, so it must not name
    // the error itself. Neither key ever appears in a worked example.
    if (key === "error" || key === "message") continue;
    // A key written by two different lines is ambiguous (an error branch and
    // the real one); keep the first and refuse any later disagreement.
    if (claimed.has(key)) { if (map[key] !== label) delete map[key]; continue; }
    claimed.add(key);
    map[key] = label;
  }
  const uses = new Map();
  for (const v of Object.values(map)) uses.set(v, (uses.get(v) || 0) + 1);
  for (const [k, v] of Object.entries(map)) if (uses.get(v) > 1) delete map[k];
  return map;
}

// The literal text a renderer puts on either side of an answer's number.
// `oP.textContent = "$" + fmt(r.annual_cost, 2) + "/yr"` reads as three
// top-level `+` terms; the one holding the single `r.<key>` reference is the
// number, and the string literals before and after it are what the reader sees
// wrapped around it. Anything else in those positions (a second variable, a
// ternary, a template) means the line is not simply "unit + number + unit",
// and the key is left bare rather than guessed at.
function splitTopLevel(expr) {
  const parts = [];
  let depth = 0, cur = "", quote = null;
  for (let i = 0; i < expr.length; i++) {
    const c = expr[i];
    if (quote) { cur += c; if (c === "\\") { cur += expr[++i] ?? ""; } else if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'" || c === "`") { quote = c; cur += c; continue; }
    if ("([{".includes(c)) depth++;
    else if (")]}".includes(c)) depth--;
    if (c === "+" && depth === 0) { parts.push(cur); cur = ""; continue; }
    cur += c;
  }
  parts.push(cur);
  return parts.map((x) => x.trim());
}

const STRING_LITERAL = /^"((?:[^"\\]|\\.)*)"$|^'((?:[^'\\]|\\.)*)'$/;
function parseOutputUnit(expr, key, aliases = DEFAULT_ALIASES, vars = ["r"]) {
  const VAR = "(?:" + vars.map((v) => v.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")";
  // A conditional line says different things about the same number; whichever
  // branch we picked would be wrong half the time.
  if (splitTopLevel(expr).length === 1 && expr.includes("?")) return null;
  const parts = splitTopLevel(expr);
  if (parts.length < 2) return null;
  const at = parts.findIndex((x) => vars.some((v) => x.includes(v + "." + key)));
  if (at < 0) return null;
  if (parts.some((x, i) => i !== at && vars.some((v) => x.includes(v + ".")))) return null;
  if (parts[at].includes("?")) return null;
  const lit = (x) => {
    const m = STRING_LITERAL.exec(x);
    if (!m) return null;
    try { return JSON.parse(m[1] !== undefined ? '"' + m[1] + '"' : JSON.stringify(m[2])); } catch { return null; }
  };
  let prefix = "", suffix = "";
  for (let i = 0; i < at; i++) { const v = lit(parts[i]); if (v === null) return null; prefix += v; }
  for (let i = at + 1; i < parts.length; i++) { const v = lit(parts[i]); if (v === null) return null; suffix += v; }
  // A long prefix is a sentence leading into the number ("Maximum allowable
  // pressure " + p + " psi"). The page already has its own caption for that,
  // but the unit trailing the number is still the unit -- so drop the prefix
  // and keep the suffix. Where there is no suffix the prefix is all the row
  // would say ("Class " + n), so it stays.
  if (suffix !== "" && (prefix.trim().length > 2 || /[A-Za-z]{3}/.test(prefix))) prefix = "";
  if (prefix === "" && suffix === "") return null;
  // A unit is short. Anything longer is a sentence about the answer, which the
  // page already has room for in the collapsed proof.
  if (suffix.length > 16 || (prefix + suffix).length > 24) return null;
  // A digit next to the number reads as part of it ("1200 3-phase").
  if (/^\s*[\d.]/.test(suffix)) return null;
  // The affix belongs to whatever the renderer PRINTS, and the segment holding
  // the key may SCALE it first: `fmt(r.contribution_margin_ratio * 100, 2) +
  // "%"` prints 60.00%, but recording "%" against the raw 0.6 made the tile
  // page read "0.6%" -- a sixty-percent margin shown as under one percent.
  // Seven pages shipped that way (contribution margin ratio, solar collector
  // efficiency, sling bend efficiency, reeving efficiency, PV capacity factor
  // and clipping onset, SVI settled fraction), and the same shape turned an
  // hour into " min" and an ohm into " milliohm".
  //
  // A plain numeric scale is recorded, so the page can print the number the
  // renderer prints rather than dropping the unit. Any OTHER arithmetic --
  // a reciprocal (`"1 / " + fmt(1 / r.recommended_hp, 0) + " HP"`), a unit
  // conversion by a named constant -- cannot be reproduced from the raw value
  // and disqualifies the affix instead. String literals are stripped first so
  // a hyphen inside one is not read as a minus.
  const KEY = { source: VAR + "\\.[A-Za-z_$][\\w$]*" };
  const FMT = "(?:" + aliases.fmt + ")";
  const scaled = parts[at].match(
    new RegExp("^" + FMT + "\\(\\s*" + KEY.source + "\\s*([*/])\\s*(\\d+(?:\\.\\d+)?)\\s*,\\s*(\\d+)\\s*\\)$"),
  );
  if (scaled) {
    const n = Number(scaled[2]);
    if (!Number.isFinite(n) || n === 0) return null;
    return { prefix, suffix, digits: Number(scaled[3]), scale: scaled[1] === "*" ? n : 1 / n };
  }
  const keySegment = parts[at].replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, "");
  if (/[*/]|(?<![\w$])-|-(?![\w$])/.test(keySegment.replace(new RegExp(VAR + "\\.[A-Za-z_$][\\w$]*", "g"), "K"))) return null;
  // How many decimals the calculator itself shows. A page that prints
  // `1.52625` where the tool prints `1.5` is quoting a precision the tool
  // never claims.
  const d = parts[at].match(new RegExp("\\b" + FMT + "\\(\\s*" + VAR + "\\.[A-Za-z_$][\\w$]*\\s*,\\s*(\\d+)\\s*\\)\\s*$"));
  const digits = d ? Number(d[1]) : null;
  return digits === null ? { prefix, suffix } : { prefix, suffix, digits };
}

// The two words a renderer prints for a BOOLEAN answer.
//
// A worked-example fixture records a boolean as 0 or 1, and the tile page
// printed that literally: `ltv` asked "PMI required?" and answered **0**, where
// the calculator itself says "No". 21 tiles read that way. The renderers state
// both words in one place -- `oPMI.textContent = r.pmi_required ? "Yes (LTV >
// 80%)" : "No";` -- so the page can use the calculator's own wording instead of
// a raw flag.
//
// Only the COMPLETE ternary is taken: the whole assignment must be the
// conditional and nothing else. Several renderers concatenate after it
// (`r.pass ? "PASS" : "FAIL (spacing " + ...`), where the literal is a fragment
// and printing it alone would truncate the answer mid-sentence.
function parseOutputBooleans(body, aliases = DEFAULT_ALIASES) {
  const vars = resultVars(body);
  const lines = new Set();
  const LINE_RE = new RegExp("\\b([A-Za-z_$][\\w$]*)\\s*=\\s*(?:\\w*(?:" + aliases.outLine + "))\\(", "g");
  for (const m of body.matchAll(LINE_RE)) lines.add(m[1]);
  if (!lines.size) return {};
  const VAR = "(?:" + vars.map((v) => v.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")";
  const RE = new RegExp(
    "([A-Za-z_$][\\w$]*)\\.textContent\\s*=\\s*" + VAR + "\\.([A-Za-z_$][\\w$]*)\\s*\\?\\s*" +
    "(\"(?:[^\"\\\\]|\\\\.)*\")\\s*:\\s*(\"(?:[^\"\\\\]|\\\\.)*\")\\s*;",
    "g",
  );
  const map = {};
  const seen = new Set();
  for (const m of body.matchAll(RE)) {
    if (!lines.has(m[1])) continue;
    const key = m[2];
    let t, f;
    try { t = JSON.parse(m[3]); f = JSON.parse(m[4]); } catch { continue; }
    if (!t.trim() || !f.trim()) continue;
    // Two lines describing the same flag differently name neither.
    if (seen.has(key)) { delete map[key]; continue; }
    seen.add(key);
    map[key] = { t, f };
  }
  return map;
}

// Walk the same `NAME.textContent = ...` assignments parseOutputLabels reads,
// but keep the units instead of the captions. Independent of the caption pass:
// a line whose caption is ambiguous can still have an unambiguous unit, and a
// captioned line can have none.
function parseOutputUnits(body, aliases = DEFAULT_ALIASES) {
  const vars = resultVars(body);
  const REF_RE = () => resultRefRe(vars, "g");
  const lines = new Set();
  const LINE_RE = new RegExp("\\b([A-Za-z_$][\\w$]*)\\s*=\\s*(?:\\w*(?:" + aliases.outLine + "))\\(", "g");
  for (const m of body.matchAll(LINE_RE)) lines.add(m[1]);
  if (lines.size === 0) return {};
  // How many display lines mention each key at all -- including the ones the
  // single-reference rule below skips. A key written by two lines has no
  // unambiguous SCALE: `riprap-d50` prints D50 on one line and the layer
  // thickness (`r.d50_in * 1.5`) on another, and reading the 1.5 off the wrong
  // line reported an 11.7 in stone as 17.6 in. A mis-read affix is usually
  // harmless -- both lines are inches -- but a mis-read scale is a wrong
  // number, so only the scale is held to this stricter test.
  const mentions = new Map();
  for (const m of body.matchAll(/([A-Za-z_$][\w$]*)\.textContent\s*=\s*([^;]*)/g)) {
    if (!lines.has(m[1])) continue;
    for (const k of new Set([...m[2].matchAll(REF_RE())].map((x) => x[1]))) {
      mentions.set(k, (mentions.get(k) || 0) + 1);
    }
  }
  const map = {};
  const seen = new Set();
  for (const m of body.matchAll(/([A-Za-z_$][\w$]*)\.textContent\s*=\s*([^;]*)/g)) {
    if (!lines.has(m[1])) continue;
    const expr = m[2].trim();
    const refs = [...new Set([...expr.matchAll(REF_RE())].map((x) => x[1]))];
    if (refs.length !== 1) continue;
    const key = refs[0];
    if (key === "error" || key === "message") continue;
    let unit = parseOutputUnit(expr, key, aliases, vars);
    if (unit && typeof unit.scale === "number" && (mentions.get(key) || 0) > 1) unit = null;
    // A key two lines write with different units is a key we cannot name.
    if (seen.has(key)) { if (!unit || JSON.stringify(map[key]) !== JSON.stringify(unit)) delete map[key]; continue; }
    seen.add(key);
    if (unit) map[key] = unit;
  }
  return map;
}

// Extract the balanced Nth (0-based) argument of the call that starts at `from`
// (the index just past the opening paren). Returns the raw source text.
function argAt(src, from, n) {
  let i = from, depth = 1, cur = "", parts = [];
  for (; i < src.length && depth > 0; i++) {
    const c = src[i];
    if ("([{".includes(c)) depth++;
    else if (")]}".includes(c)) { depth--; if (depth === 0) break; }
    if (c === "," && depth === 1) { parts.push(cur); cur = ""; } else cur += c;
  }
  parts.push(cur);
  return parts[n] === undefined ? null : parts[n].trim();
}

// Find `NAME = makeSelect("label", "id", OPTS)` / `makeNumber("label","id",ATTRS)`
// declarations in a render function body, keyed by the local variable NAME.
// `ns` is the renderer module's namespace, used to resolve non-literal OPTS.
function parseFields(body, ns, aliases = DEFAULT_ALIASES) {
  const fields = new Map();
  // makeSelect: the options argument is balanced-parsed, then evaluated against
  // the module namespace; a literal array falls back to the regex scrape.
  const re = new RegExp("\\b([A-Za-z_$][\\w$]*)\\s*=\\s*(?:\\w*(?:" + aliases.select + "))\\(\\s*(\"(?:[^\"\\\\]|\\\\.)*\")\\s*,\\s*(\"(?:[^\"\\\\]|\\\\.)*\")\\s*,", "g");
  let m;
  while ((m = re.exec(body))) {
    const expr = argAt(body, m.index + m[0].length, 0);
    if (expr === null) continue;
    const options = (ns ? evalOptions(expr, ns) : null) || parseOptions(expr);
    fields.set(m[1], { kind: "select", label: JSON.parse(m[2]), options });
  }
  // makeNumber(label, id[, attrs]) -- three args (the id is required); attrs is
  // the optional 4th capture.
  const NUM_RE = new RegExp("\\b([A-Za-z_$][\\w$]*)\\s*=\\s*(?:\\w*(?:" + aliases.number + "))\\(\\s*(\"(?:[^\"\\\\]|\\\\.)*\")\\s*,\\s*(\"(?:[^\"\\\\]|\\\\.)*\")\\s*(?:,\\s*(\\{[^}]*\\}))?\\s*\\)", "g");
  for (const m of body.matchAll(NUM_RE)) {
    if (fields.has(m[1])) continue;
    let attrs = null;
    if (m[4]) { try { attrs = JSON.parse(m[4].replace(/([{,]\s*)([A-Za-z_]\w*):/g, '$1"$2":').replace(/'/g, '"')); } catch { attrs = null; } }
    fields.set(m[1], { kind: "number", label: JSON.parse(m[2]), attrs });
  }
  return fields;
}

// The tile's citation string, set literally on citationEl at the top of the
// renderer (the same text the browser shows in the citation footer).
function parseCitation(body) {
  const m = body.match(/citationEl\.textContent\s*=\s*("(?:[^"\\]|\\.)*")\s*;/);
  return m ? JSON.parse(m[1]) : null;
}

// Map each compute-param key to the field variable that supplies it, by scanning
// the whole renderer body for `key: [Number(]VAR.(select|input).value`. This is
// the object the renderer passes to its compute (whether inline `compute({...})`,
// a `const p = {...}` variable, or a `runInWorker({inputs}, fn)` call). The
// pattern is specific enough that literal `fillExample({...})` default objects
// (string/number values, not `.select.value`) never match. First mapping wins.
function parseComputeCall(body) {
  const map = new Map();
  // Matches both an explicit object property (`key: fieldvar.input.value`) and
  // an intermediate const later used as object shorthand
  // (`const key = Number(fieldvar.input.value)` then `{ ..., key }`) -- the `[:=]`
  // covers both. Spurious matches to non-params are ignored (only real compute
  // params are looked up).
  for (const m of body.matchAll(/([A-Za-z_$][\w$]*)\s*[:=]\s*(Number\(\s*)?([A-Za-z_$][\w$]*)\.(select|input)\.value/g)) {
    if (!map.has(m[1])) map.set(m[1], { var: m[3], coerced: Boolean(m[2]), accessor: m[4] });
  }
  return map;
}

// A looser field parser, for LABELS ONLY (never for BESPOKE_SCHEMAS).
//
// parseFields above must resolve a select's literal {value,label} options,
// because a schema advertises that enum to run(). A label needs none of that --
// only the field's own label and the variable holding it. So this pass takes
// any `NAME = makeX("Label", "id", ...)` regardless of what follows, which
// picks up two families the strict parser drops: selects whose options come
// from a function (`makeSelect("AWG size", "awgg-awg", awgOptions())`), and the
// text/textarea/row factories it never modelled at all.
// The `[\w$]*` before `make` matters: several modules namespace their copy of
// the factory (`_v26makeNumber`, `_v8w_makeNumber`), and anchoring on a bare
// `make` skipped every one of those renderers.
const LOOSE_FACTORY = /\b([A-Za-z_$][\w$]*)\s*=\s*[\w$]*make(?:Number|Select|Text|Textarea|RowField)\(\s*("(?:[^"\\]|\\.)*")\s*,/g;
function parseFieldsLoose(body, aliases = DEFAULT_ALIASES) {
  const fields = new Map();
  const RE = new RegExp("\\b([A-Za-z_$][\\w$]*)\\s*=\\s*(?:\\w*(?:" + aliases.anyInput + "))\\(\\s*(\"(?:[^\"\\\\]|\\\\.)*\")\\s*,", "g");
  for (const m of body.matchAll(RE)) {
    if (fields.has(m[1])) continue;
    let label;
    try { label = JSON.parse(m[2]); } catch { continue; }
    fields.set(m[1], { label });
  }
  return fields;
}

// A looser key->field map, for LABELS ONLY (never for BESPOKE_SCHEMAS).
//
// parseComputeCall above insists on `key: VAR.input.value`, because a schema
// feeds run() and a mis-parse there would advertise an input run cannot honor.
// But most renderers the strict pass gives up on simply route the field through
// a reader first -- `span_ft: readNum(span.input)`, `w_plf: num(w.input)` --
// which is the same linkage wearing a helper. A label is only ever displayed,
// so that is enough to name the field, and 187 tiles were skipped for it.
function parseComputeCallLoose(body) {
  const map = new Map();
  for (const m of body.matchAll(/([A-Za-z_$][\w$]*)\s*[:=]\s*[A-Za-z_$][\w$]*\(\s*([A-Za-z_$][\w$]*)\.(select|input)\b/g)) {
    if (!map.has(m[1])) map.set(m[1], { var: m[2] });
  }
  return map;
}

async function computeParams(reg) {
  const mod = await import(new URL(reg.module, CMAP_URL).href);
  const fn = mod[reg.fn];
  if (typeof fn !== "function") return null;
  const s = fn.toString();
  const o = s.indexOf("("); const b = s.indexOf("{", o);
  if (b < 0 || s.slice(o, b).includes(")")) return [];
  let d = 0, e = -1;
  for (let i = b; i < s.length; i++) { if (s[i] === "{") d++; else if (s[i] === "}") { d--; if (!d) { e = i; break; } } }
  const parts = []; d = 0; let cur = "";
  for (const ch of s.slice(b + 1, e)) { if ("([{".includes(ch)) d++; else if (")]}".includes(ch)) d--; if (ch === "," && !d) { parts.push(cur); cur = ""; } else cur += ch; }
  if (cur.trim()) parts.push(cur);
  return parts.map((p) => {
    const eq = p.indexOf("=");
    const name = (eq < 0 ? p : p.slice(0, eq)).trim();
    if (!name || name.startsWith("...")) return null;
    // Classify the default so a string-select mapped to a number/boolean param
    // (a type-mismatch that would break enum validation) can be rejected.
    let defType = "none", defValue = null;
    if (eq >= 0) {
      const raw = p.slice(eq + 1).trim();
      if (/^["']/.test(raw)) defType = "string";
      else if (/^(true|false)\b/.test(raw)) defType = "boolean";
      else if (/^-?\d/.test(raw)) defType = "number";
      else defType = "other";
      try { defValue = JSON.parse(raw.replace(/'/g, '"')); } catch { defValue = null; }
    }
    return { name, defType, defValue };
  }).filter(Boolean);
}

async function main() {
  const { RENDERER_MAP } = await import(new URL("test/fixtures/renderer-map.js", ROOT).href);
  const { COMPUTE_MAP } = await import(CMAP_URL.href);
  const modCache = new Map();
  const aliasCache = new Map();
  const moduleAliases = (rel) => {
    let a = aliasCache.get(rel);
    if (!a) { a = factoryAliases(readFileSync(new URL(rel, CMAP_URL), "utf8")); aliasCache.set(rel, a); }
    return a;
  };
  const imp = async (rel) => { const u = new URL(rel, CMAP_URL).href; let m = modCache.get(u); if (!m) { m = await import(u); modCache.set(u, m); } return m; };

  const emitted = {};
  const labels = {};
  const outLabels = {};
  const outUnits = {};
  const outBools = {};
  const stats = { total: 0, alreadySchema: 0, emitted: 0, skip_no_call: 0, skip_numeric_select: 0, skip_unmapped: 0, skip_no_selects: 0 };
  const samples = [];

  for (const id of Object.keys(RENDERER_MAP)) {
    stats.total++;
    const rreg = RENDERER_MAP[id];
    const rmod = await imp(rreg.module);
    const rf = rmod[rreg.exportName] && rmod[rreg.exportName][id];
    if (!rf) continue;
    if (rf.schema) { stats.alreadySchema++; continue; }
    const body = rf.toString();
    const aliases = moduleAliases(rreg.module);
    const outMap = parseOutputLabels(body, aliases);
    if (Object.keys(outMap).length) outLabels[id] = outMap;
    const unitMap = parseOutputUnits(body, aliases);
    if (Object.keys(unitMap).length) outUnits[id] = unitMap;
    const boolMap = parseOutputBooleans(body, aliases);
    if (Object.keys(boolMap).length) outBools[id] = boolMap;
    const fields = parseFields(body, rmod, aliases);
    const callMap = parseComputeCall(body);
    const params = await computeParams(COMPUTE_MAP[id]);
    // Labels first, and from the loose map as well: they are display-only, so
    // they are collected even for the tiles the strict schema pass rejects
    // below. Strict wins where both resolve.
    if (params) {
      const loose = parseComputeCallLoose(body);
      const looseFields = parseFieldsLoose(body, aliases);
      const labelMap = {};
      for (const { name: key } of params) {
        const ref = callMap.get(key) || loose.get(key);
        const field = ref && (fields.get(ref.var) || looseFields.get(ref.var));
        if (field && typeof field.label === "string" && field.label.trim()) labelMap[key] = field.label.trim();
      }
      // A label two params share cannot identify either of them: refrigerant-pt
      // has one "Value" box feeding pressure_psig or temperature_F depending on
      // a mode select, and "Value 122" says less than "pressure_psig 122".
      const uses = new Map();
      for (const v of Object.values(labelMap)) uses.set(v, (uses.get(v) || 0) + 1);
      for (const [k, v] of Object.entries(labelMap)) if (uses.get(v) > 1) delete labelMap[k];
      if (Object.keys(labelMap).length) labels[id] = labelMap;
    }
    // Fall back to the loose key->field map when the strict one finds nothing.
    //
    // The strict pass insists on `key: VAR.input.value`, and the loose one also
    // accepts the same linkage wearing a helper -- `span_ft: readNum(span.input)`.
    // The loose map fed LABELS ONLY, on the reasoning that a schema reaches
    // run() and a mis-parse there would advertise an input run cannot honor.
    //
    // Two things bound that risk, and they are both already in place. A bad KEY
    // cannot survive: `schemaIfConsistent` drops any schema whose keys are not
    // real compute params, and check-both-doors asserts every advertised name is
    // sendable and every example key is advertised, on all 1,804 tiles. What is
    // left is a bad LABEL on a good key, and that is measurable -- so it was
    // measured rather than assumed:
    //
    //   - all three query-fill lenses UNCHANGED: 4,154 / 4,680 / 1,942 recovered
    //     at 0 / 0 / 7 wrong, identical to before;
    //   - 277 unit-suffixed keys checked against their labels across the 154
    //     newly-covered tiles, with one heuristic false positive
    //     (`feed_ipr_in` -> "Feed per revolution f (IPR)", which is right);
    //   - 36 key/label pairs read by hand, all correct.
    //
    // skip_no_call falls from 188 to 32.
    const effectiveCallMap = (callMap && callMap.size) ? callMap : parseComputeCallLoose(body);
    if (!effectiveCallMap || effectiveCallMap.size === 0) { stats.skip_no_call++; continue; }
    if (!params) { stats.skip_no_call++; continue; }

    // Include every compute param we can confidently map to a parsed field
    // (a subset is safe — schemaIfConsistent only needs inputs ⊆ params). But a
    // numeric-coerced select (Number(x.select.value)) is a hard skip for the
    // WHOLE tile: run() would feed the compute a string it coerces differently,
    // a silent-wrong-value risk we refuse to introduce.
    let typeMismatch = false, hasSelect = false, anyUnmapped = false;
    const inputs = [];
    for (const { name: key, defType, defValue } of params) {
      const ref = effectiveCallMap.get(key);
      if (!ref) { anyUnmapped = true; continue; } // param not sourced from a field
      let field = fields.get(ref.var);
      if (!field) { anyUnmapped = true; continue; }
      if (field.kind === "select") {
        if (defType === "boolean") { typeMismatch = true; break; }
        if (!field.options || field.options.length === 0) { anyUnmapped = true; continue; } // dynamic options — omit
        if (ref.coerced) {
          // The renderer itself does `Number(sel.select.value)`, so the compute
          // wants a number. Publish the enum as numbers and run() hands over
          // exactly what the page does. If any option is not a finite number
          // the two paths would diverge, so refuse the whole tile.
          if (!field.options.every((o) => o.value !== "" && Number.isFinite(Number(o.value)))) { typeMismatch = true; break; }
          field = { ...field, options: field.options.map((o) => ({ value: Number(o.value), label: o.label })) };
        } else if (defType === "number") {
          // Uncoerced: the page submits the option string. A numeric compute
          // default says it wanted a number — the mismatch is the renderer's,
          // and guessing either way could feed a wrong value. Refuse.
          typeMismatch = true; break;
        }
        hasSelect = true;
      }
      inputs.push({ key, label: field.label, kind: field.kind, options: field.kind === "select" ? field.options : null, default: defValue ?? null, attrs: field.attrs ?? null });
    }
    if (typeMismatch) { stats.skip_numeric_select++; continue; }
    if (inputs.length === 0) { stats.skip_no_fields = (stats.skip_no_fields || 0) + 1; continue; }
    // A partial schema is kept, for a numeric tile as well as a select one.
    //
    // The old rule refused a pure-numeric tile that did not map EVERY param, on
    // the grounds that "introspection alone is just as good". That was true when
    // a schema's only payoff was its enum values. It is not true now: a schema
    // also carries the field's LABEL and its min/max, which introspection cannot
    // give (it reads a compute signature, which has no captions), and those feed
    // the range warnings on `run` and the field index the website's one-box
    // reads. `describe` already completes a partial schema from introspection,
    // so the unmapped params are still named -- richly where known, plainly
    // where not.
    void anyUnmapped;
    const citation = parseCitation(body);
    emitted[id] = citation ? { inputs, citation } : { inputs };
    stats.emitted++;
    if (samples.length < 8) samples.push({ id, inputs });
  }

  // Correctness check: every emitted select's worked-example value must be one
  // of the extracted options. A miss means the parse got the options wrong.
  const examples = new Map();
  for (const row of JSON.parse(readFileSync(new URL("test/fixtures/worked-examples.json", ROOT), "utf8")).rows) {
    if (!examples.has(row.tile_id)) examples.set(row.tile_id, row.inputs);
  }
  const mismatches = [];
  for (const [id, sc] of Object.entries(emitted)) {
    const ex = examples.get(id);
    if (!ex) continue;
    for (const f of sc.inputs) {
      if (f.kind !== "select") continue;
      const v = ex[f.key];
      if (v === undefined) continue;
      if (!f.options.some((o) => String(o.value) === String(v))) mismatches.push(`${id}.${f.key}: example ${JSON.stringify(v)} not in ${JSON.stringify(f.options.map((o) => o.value))}`);
    }
  }
  // Belt and suspenders: drop any tile whose worked example still contradicts
  // its extracted options, so the shipped set is provably example-consistent.
  const dropped = new Set(mismatches.map((m) => m.split(".")[0]));
  for (const id of dropped) delete emitted[id];
  stats.emitted = Object.keys(emitted).length;
  stats.dropped_by_example_check = dropped.size;

  const labelOnly = Object.keys(labels).filter((id) => !emitted[id]);
  if (!check) console.log("bespoke-schema extraction:", JSON.stringify(stats, null, 2));
  if (!check) console.log(`label maps: ${Object.keys(labels).length} tiles (${labelOnly.length} that get NO schema)`);
  if (!check) console.log(`output-label maps: ${Object.keys(outLabels).length} tiles`);
  if (dropped.size) { console.log("\nDROPPED (example contradicts extracted options):"); for (const m of mismatches) console.log("  " + m); }
  if (verbose || (!write && !check)) {
    for (const s of samples) {
      console.log(`\n${s.id}:`);
      for (const i of s.inputs) console.log(`  ${i.key} [${i.kind}]${i.options ? " opts=" + JSON.stringify(i.options.map((o) => o.value)) : ""}`);
    }
  }
  const fixture = renderFixture(emitted);
  const labelFixture = renderLabelFixture(labels);
  const outLabelFixture = renderOutputLabelFixture(outLabels);
  const outUnitFixture = renderOutputUnitFixture(outUnits);
  const outBoolFixture = renderOutputBoolFixture(outBools);
  if (write) {
    writeFileSync(FIXTURE_URL, fixture);
    console.log(`\nwrote ${stats.emitted} bespoke schemas to test/fixtures/bespoke-schemas.js`);
    writeFileSync(LABELS_URL, labelFixture);
    console.log(`wrote ${Object.keys(labels).length} label maps to test/fixtures/bespoke-labels.js`);
    writeFileSync(OUT_LABELS_URL, outLabelFixture);
    console.log(`wrote ${Object.keys(outLabels).length} output-label maps to test/fixtures/bespoke-output-labels.js`);
    writeFileSync(OUT_UNITS_URL, outUnitFixture);
    console.log(`wrote ${Object.keys(outUnits).length} output-unit maps to test/fixtures/bespoke-output-units.js`);
    writeFileSync(OUT_BOOLS_URL, outBoolFixture);
    console.log(`wrote ${Object.keys(outBools).length} output-boolean maps to test/fixtures/bespoke-output-bools.js`);
  } else if (check) {
    let current = "";
    try { current = readFileSync(FIXTURE_URL, "utf8"); } catch { /* missing */ }
    if (current !== fixture) {
      console.error("✗ bespoke-schemas.js is stale: a renderer's fields/options changed but the fixture was not regenerated. Run `node scripts/extract-bespoke-schemas.mjs --write` and commit.");
      process.exit(1);
    }
    console.log(`✓ bespoke-schemas.js is in sync (${stats.emitted} tiles).`);
    let currentLabels = "";
    try { currentLabels = readFileSync(LABELS_URL, "utf8"); } catch { /* missing */ }
    if (currentLabels !== labelFixture) {
      console.error("✗ bespoke-labels.js is stale: a renderer's field labels changed but the fixture was not regenerated. Run `node scripts/extract-bespoke-schemas.mjs --write` and commit.");
      process.exit(1);
    }
    console.log(`✓ bespoke-labels.js is in sync (${Object.keys(labels).length} tiles).`);
    let currentOut = "";
    try { currentOut = readFileSync(OUT_LABELS_URL, "utf8"); } catch { /* missing */ }
    if (currentOut !== outLabelFixture) {
      console.error("✗ bespoke-output-labels.js is stale: a renderer's output captions changed but the fixture was not regenerated. Run `node scripts/extract-bespoke-schemas.mjs --write` and commit.");
      process.exit(1);
    }
    console.log(`✓ bespoke-output-labels.js is in sync (${Object.keys(outLabels).length} tiles).`);
    let currentUnits = "";
    try { currentUnits = readFileSync(OUT_UNITS_URL, "utf8"); } catch { /* missing */ }
    if (currentUnits !== outUnitFixture) {
      console.error("✗ bespoke-output-units.js is stale: a renderer's answer units changed but the fixture was not regenerated. Run `node scripts/extract-bespoke-schemas.mjs --write` and commit.");
      process.exit(1);
    }
    console.log(`✓ bespoke-output-units.js is in sync (${Object.keys(outUnits).length} tiles).`);
    let currentBools = "";
    try { currentBools = readFileSync(OUT_BOOLS_URL, "utf8"); } catch { /* missing */ }
    if (currentBools !== outBoolFixture) {
      console.error("✗ bespoke-output-bools.js is stale: a renderer's yes/no wording changed but the fixture was not regenerated. Run `node scripts/extract-bespoke-schemas.mjs --write` and commit.");
      process.exit(1);
    }
    console.log(`✓ bespoke-output-bools.js is in sync (${Object.keys(outBools).length} tiles).`);
  }
}


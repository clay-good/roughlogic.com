#!/usr/bin/env node
// v8 Phase A manifest-discipline lint (spec-v8.md §3).
//
// Verifies that every data/<folder>/manifest.json carries the v6 edition
// stamp (already enforced by check-v6-discipline) and the v8 asOf date.
// Verifies that every shard listed in every manifest has a recorded hash.
// Future-proofs against state-keyed shards by checking that any
// data/legal/* (when introduced) carries a per-entry verifiedOn date.
//
// Pure read-and-report; no network, no mutation.

import { readFile, readdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { existsSync } from "node:fs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = resolve(ROOT, "data");

const errors = [];
const warnings = [];

function isIsoDate(s) {
  return typeof s === "string" && /^\d{4}-\d{2}-\d{2}$/.test(s);
}

async function main() {
  const folders = (await readdir(DATA, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name);
  for (const folder of folders) {
    const manifestPath = resolve(DATA, folder, "manifest.json");
    if (!existsSync(manifestPath)) continue;
    const m = JSON.parse(await readFile(manifestPath, "utf8"));
    // edition (v6 §2.6 / §7)
    if (!m.edition || typeof m.edition !== "string" || m.edition.length === 0) {
      errors.push("data/" + folder + "/manifest.json missing 'edition' (v8 §A.1).");
    }
    // asOf (v8 §A.2)
    if (!isIsoDate(m.asOf)) {
      errors.push("data/" + folder + "/manifest.json missing or invalid 'asOf' ISO date (v8 §A.2).");
    }
    // every listed shard has a recorded hash
    for (const shard of m.shards || []) {
      if (!m.hashes || !m.hashes[shard.file]) {
        errors.push("data/" + folder + "/manifest.json shard '" + shard.file + "' has no recorded hash.");
      }
    }
  }
  // A manifest's 'edition' is the reader-facing disclosure of what the bundled
  // values follow, and it is GENERATED by scripts/build-data.mjs. Two of them
  // had been hand-edited after generation to say that the bundled 2021 I-codes
  // are a cycle behind the published 2024 ones -- a sentence the generator did
  // not carry, so the next `npm run data:refresh` deleted it. The weekly
  // data-refresh workflow runs exactly that command, so a maintainer disclosure
  // was one cron tick from vanishing with nobody looking. Every edition string
  // on disk must therefore be reproducible from the generator: compare with the
  // build dates blanked, since those legitimately move on every refresh.
  const generator = await readFile(resolve(ROOT, "scripts", "build-data.mjs"), "utf8");
  const undated = (s) => s.replace(/\d{4}-\d{2}-\d{2}/g, "<date>");
  const generated = new Map();
  // The interpolated token used to be `TODAY` only. Matching it by name meant
  // this parser encoded HOW the generator was written, and it broke the moment
  // CF-05 moved those dates to a committed EDITION_VERIFIED map -- reporting
  // twelve editions as hand-edited drift. Accept any dotted identifier here;
  // `undated()` blanks whatever it resolves to anyway.
  for (const m of generator.matchAll(
    /folder:\s*"([a-z-]+)",\s*edition:\s*"((?:[^"\\]|\\.)*)"(?:\s*\+\s*[A-Za-z_$][\w$]*(?:\.[\w$]+)*\s*\+\s*"((?:[^"\\]|\\.)*)")?/g,
  )) {
    const raw = (m[2] + (m[3] === undefined ? "" : "<date>" + m[3])).replace(/\\"/g, '"');
    generated.set(m[1], undated(raw));
  }
  if (generated.size === 0) {
    errors.push("check-manifests could not read any manifest edition from scripts/build-data.mjs; the parser has drifted.");
  }
  for (const [folder, expected] of generated) {
    const manifestPath = resolve(DATA, folder, "manifest.json");
    if (!existsSync(manifestPath)) {
      errors.push("scripts/build-data.mjs emits folder '" + folder + "', but data/" + folder + "/manifest.json is missing.");
      continue;
    }
    const m = JSON.parse(await readFile(manifestPath, "utf8"));
    if (undated(String(m.edition)) !== expected) {
      errors.push(
        "data/" + folder + "/manifest.json 'edition' is not what scripts/build-data.mjs produces, so the next " +
          "data:refresh would overwrite it. Move the wording into the generator.",
      );
    }
  }

  // A folder declares a `refresh_cadence`, and the shards under it carry
  // `verified_on` / `verifiedOn` stamps. Nothing compared the two. On 2026-09-02
  // exactly one folder was over its own declared cadence -- data/legal, whose 48
  // post-Wayfair nexus stamps all read 2025-01-15 against a **quarterly** promise
  // that docs/data-sources.md spells out as "quarterly recheck against the state
  // source page (oldest verified_on first)". Twenty months, and the only thing
  // that would have noticed was somebody opening the file.
  //
  // Warn from one cadence period. Fail at four, because a value four rechecks
  // late is not late, it is unmaintained -- unless the manifest carries a
  // `staleness_note` saying so out loud, which is the CF-03 shape: an
  // acknowledgement that lives in a diff-reviewable file rather than in a
  // warning nobody reads.
  const CADENCE_DAYS = {
    daily: 1, weekly: 7, monthly: 31, quarterly: 92, annual: 366,
    "event-driven": null,
  };
  const DAY_MS = 86400000;
  const now = Date.now();

  function stamps(value, into) {
    if (Array.isArray(value)) {
      for (const v of value) stamps(v, into);
      return;
    }
    if (!value || typeof value !== "object") return;
    for (const key of ["verified_on", "verifiedOn"]) {
      if (isIsoDate(value[key])) into.push(value[key]);
    }
    for (const v of Object.values(value)) stamps(v, into);
  }

  async function shardFiles(dir) {
    const found = [];
    for (const e of await readdir(dir, { withFileTypes: true })) {
      const full = resolve(dir, e.name);
      if (e.isDirectory()) found.push(...(await shardFiles(full)));
      else if (e.name.endsWith(".json") && e.name !== "manifest.json") found.push(full);
    }
    return found;
  }

  for (const folder of folders) {
    const manifestPath = resolve(DATA, folder, "manifest.json");
    if (!existsSync(manifestPath)) continue;
    const m = JSON.parse(await readFile(manifestPath, "utf8"));
    const budget = CADENCE_DAYS[m.refresh_cadence];
    if (!budget) continue; // event-driven, or a cadence this table does not know
    const all = [];
    for (const f of await shardFiles(resolve(DATA, folder))) {
      stamps(JSON.parse(await readFile(f, "utf8")), all);
    }
    if (all.length === 0) continue;
    const oldest = all.sort()[0];
    const ageDays = Math.floor((now - Date.parse(oldest + "T00:00:00Z")) / DAY_MS);
    if (ageDays <= budget) continue;
    const line =
      "data/" + folder + " declares refresh_cadence '" + m.refresh_cadence + "' (" + budget +
      " days) but its oldest verified_on is " + oldest + ", " + ageDays + " days ago, across " +
      all.length + " stamp(s).";
    if (ageDays > budget * 4 && typeof m.staleness_note !== "string") {
      errors.push(
        line + " That is more than four rechecks late. Re-verify against the source and re-stamp, " +
          "or add a 'staleness_note' to the manifest saying what is stale and what it would take to fix.",
      );
    } else {
      warnings.push(line + " Re-verify oldest-first against the source and re-stamp.");
    }
  }

  // Future-proof: data/legal/* per-entry verifiedOn check.
  const legalDir = resolve(DATA, "legal");
  if (existsSync(legalDir)) {
    const files = await readdir(legalDir);
    for (const f of files) {
      if (!f.endsWith(".json") || f === "manifest.json") continue;
      const body = JSON.parse(await readFile(resolve(legalDir, f), "utf8"));
      // Per-state shards typically have a top-level object keyed by state code.
      for (const k of Object.keys(body)) {
        const entry = body[k];
        if (entry && typeof entry === "object" && !Array.isArray(entry) && !isIsoDate(entry.verifiedOn)) {
          errors.push("data/legal/" + f + " entry '" + k + "' missing per-entry 'verifiedOn' ISO date (v8 §A.3 future-proof).");
        }
      }
    }
  }

  for (const w of warnings) console.warn("WARN: " + w);

  if (errors.length > 0) {
    for (const e of errors) console.error("ERROR: " + e);
    console.error("v8 manifest-discipline lint FAILED with " + errors.length + " errors.");
    process.exit(1);
  }
  console.log(
    "v8 manifest-discipline lint OK (edition + asOf + shard hashes present; every edition string " +
      "reproducible from scripts/build-data.mjs; every verified_on inside its folder cadence)" +
      (warnings.length > 0 ? " with " + warnings.length + " staleness warning(s)." : "."),
  );
}

await main();

#!/usr/bin/env node
// build-catalog-lead.mjs -- the browser's catalog, with descriptions split.
//
// tools-data.js holds one row per tile and stays the single source of truth:
// every build script, every gate and the agent door read it. But descriptions
// are nine tenths of it, and the browser was downloading all of it (714 KB
// gzipped at 2,258 tiles) to route ONE deep link, which needs one row's name
// and opening sentence. docs/performance.md measured the shapes; this is the
// one it called "the same array in the same order with fewer fields per row":
//
//   tools-lead.js          every tile, in tools-data.js order, with `desc`
//                          cut to its opening sentence and `more: 1` when a
//                          remainder exists. This is what app.js imports.
//   data/desc/<x>.json     the remainder of each description, sharded by the
//                          first character of the tile id. A tile view fetches
//                          its one shard; search fetches all of them in
//                          parallel and restores every description before it
//                          ranks, so results are identical to the full file.
//
// Two properties are asserted here for every tile, because both are what make
// the split invisible:
//   1. lead + remainder === the original description, character for character.
//   2. leadSentence(lead) === leadSentence(original), so the sentence the page
//      shows under the title is the same one before and after the shard lands.
// A tile where the cut would break (2) keeps its whole description in the
// catalog and has no remainder.
//
// Same order matters: constant-notes.js decodes a bitmap by catalog POSITION.
//
// Run with --check in lint; without it, to regenerate after a catalog change.

import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { stampIntegrityAnchor } from "./stamp-integrity-anchor.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = resolve(ROOT, "data", "desc");
const LEAD_PATH = resolve(ROOT, "tools-lead.js");
const CHECK = process.argv.includes("--check");
const VERBOSE = process.argv.includes("--verbose");

// The manifest's edition stamp. A literal, not `new Date()`: a generated file
// must not change because the calendar did. Bump it when the shard shape does.
const EDITION_DATE = "2026-10-10";
// Fetched on a phone on a job site, one per tile view. The largest letter
// shard was 53 KB gzipped when this was written.
const SHARD_GZIP_CAP = 96 * 1024;

const { TOOLS } = await import(pathToFileURL(resolve(ROOT, "tools-data.js")).href);
const { firstSentence, leadSentence } = await import(pathToFileURL(resolve(ROOT, "text-lead.js")).href);
const { descBucket } = await import(pathToFileURL(resolve(ROOT, "desc-bucket.js")).href);

const rows = [];
const shards = new Map(); // bucket -> { tileId: remainder }
let kept = 0;
for (const tool of TOOLS) {
  const full = String(tool.desc);
  let lead = firstSentence(full);
  // The cut must be a true prefix and must not change the sentence the page
  // prints; otherwise the whole description stays in the catalog.
  if (!full.startsWith(lead) || lead.length === full.length || leadSentence(lead) !== leadSentence(full)) lead = full;
  const rest = full.slice(lead.length);
  if (lead + rest !== full) {
    console.error(`build-catalog-lead FAIL: ${tool.id} does not reconstruct.`);
    process.exit(1);
  }
  const row = { ...tool, desc: lead };
  if (rest) {
    row.more = 1;
    const b = descBucket(tool.id);
    if (!shards.has(b)) shards.set(b, {});
    shards.get(b)[tool.id] = rest;
  } else {
    kept++;
  }
  rows.push(row);
}

const header =
  "// GENERATED by scripts/build-catalog-lead.mjs from tools-data.js. Do not edit.\n" +
  "// The browser's catalog: every tile in tools-data.js order, `desc` cut to its\n" +
  "// opening sentence. `more: 1` marks a tile whose remainder lives in\n" +
  "// data/desc/<bucket>.json (see desc-bucket.js). tools-data.js stays the source\n" +
  "// of truth for every build script, gate and the agent door.\n";
const leadText = header + "export const TOOLS = [\n" + rows.map((r) => "  " + JSON.stringify(r) + ",").join("\n") + "\n];\n";

let drift = 0;
async function emit(path, text, label) {
  if (CHECK) {
    let existing = null;
    try { existing = await readFile(path, "utf8"); } catch { existing = null; }
    if (existing !== text) {
      console.error(`build-catalog-lead FAIL: ${label} is stale. Run: node scripts/build-catalog-lead.mjs`);
      drift++;
    }
  } else {
    await writeFile(path, text, "utf8");
  }
}

await emit(LEAD_PATH, leadText, "tools-lead.js");

if (!CHECK) await mkdir(OUT_DIR, { recursive: true });
const written = [];
for (const [b, rest] of [...shards].sort((a, c) => (a[0] < c[0] ? -1 : 1))) {
  const text = JSON.stringify({ version: 1, bucket: b, rest }) + "\n";
  const gz = gzipSync(Buffer.from(text)).length;
  if (gz > SHARD_GZIP_CAP) {
    console.error(`build-catalog-lead FAIL: shard ${b}.json is ${(gz / 1024).toFixed(1)} KB gzip, over the ${SHARD_GZIP_CAP / 1024} KB cap. Split the bucket in desc-bucket.js; do not raise the cap.`);
    process.exit(1);
  }
  written.push({ b, tiles: Object.keys(rest).length, gz, text });
  await emit(resolve(OUT_DIR, `${b}.json`), text, `data/desc/${b}.json`);
}

// A shard for a bucket that no longer exists would be served forever.
{
  let present = [];
  try { present = await readdir(OUT_DIR); } catch { present = []; }
  const expected = new Set(written.map((w) => `${w.b}.json`));
  for (const name of present) {
    if (name === "manifest.json" || !name.endsWith(".json") || expected.has(name)) continue;
    console.error(`build-catalog-lead FAIL: data/desc/${name} has no matching bucket. Delete it.`);
    process.exit(1);
  }
}

const sha256Hex = (text) => createHash("sha256").update(text, "utf8").digest("hex");
const manifestPath = resolve(OUT_DIR, "manifest.json");
const manifestText = JSON.stringify({
  name: "desc",
  version: EDITION_DATE,
  fetched: EDITION_DATE,
  edition:
    "Original project-authored tile descriptions, split from tools-data.js: the part of each " +
    "description after its opening sentence. Derived data: tools-data.js is authoritative and " +
    "these shards regenerate from it. Not from any external standard.",
  asOf: EDITION_DATE,
  // The real cadence is every catalog change: --check regenerates these shards
  // and fails on any drift, which is stricter than a date.
  refresh_cadence: "annual",
  shards: written.map((w) => ({
    file: `${w.b}.json`,
    name: `Tile descriptions after the opening sentence, ${w.b} runtime shard (generated)`,
    gzip_size_bytes: w.gz,
  })),
  hashes: Object.fromEntries(written.map((w) => [`${w.b}.json`, sha256Hex(w.text)])),
}, null, 2) + "\n";

// gzip_size_bytes varies a few bytes across zlib builds (macOS vs CI Linux) and
// is informational, so --check compares everything else.
const manifestShape = (m) => JSON.stringify({ ...m, shards: (m.shards || []).map((s) => ({ file: s.file, name: s.name })) });
if (CHECK) {
  let existing = null;
  try { existing = JSON.parse(await readFile(manifestPath, "utf8")); } catch { existing = null; }
  if (!existing || manifestShape(existing) !== manifestShape(JSON.parse(manifestText))) {
    console.error("build-catalog-lead FAIL: data/desc/manifest.json is stale. Run: node scripts/build-catalog-lead.mjs");
    drift++;
  }
} else {
  await writeFile(manifestPath, manifestText, "utf8");
  // Both hash registries carry the manifest: data/integrity.json (runtime) and
  // scripts/expected-hashes.json (`npm run data:verify` in CI).
  await stampIntegrityAnchor("desc");
}

if (drift) process.exit(1);

const leadGz = gzipSync(Buffer.from(leadText)).length;
const restGz = written.reduce((n, w) => n + w.gz, 0);
if (VERBOSE) for (const w of written) console.log(`  ${w.b}.json  ${String(w.tiles).padStart(4)} tiles  ${(w.gz / 1024).toFixed(1)} KB gzip`);
console.log(
  `build-catalog-lead: ${CHECK ? "clean" : "wrote"} tools-lead.js (${rows.length} tiles, ${(leadGz / 1024).toFixed(1)} KB gzip) and ` +
  `${written.length} description shards (${(restGz / 1024).toFixed(1)} KB gzip total, largest ${(Math.max(...written.map((w) => w.gz)) / 1024).toFixed(1)} KB); ` +
  `${kept} tile(s) keep their whole description in the catalog.`,
);

#!/usr/bin/env node
// spec-v1185 attribution: expose the citation string for bespoke (hand-written)
// renderers over MCP. Factory tiles carry their citation on render.schema (the
// retained spec.citation); hand-written renderers set it literally on citationEl
// (`citationEl.textContent = "Citation: ..."`). That single literal assignment
// is trivially and reliably parsed from the renderer's own source. This emits a
// map the catalog reads so `describe_calculator` can attribute a result -- name
// the cited standard and section -- for the ~800 bespoke tiles that otherwise
// returned citation.text: null.
//
// Only literal assignments are captured (factory renderers use the spec.citation
// variable and are correctly skipped); tiles already carrying a citation via an
// extracted input schema (bespoke-schemas.js) are skipped to avoid redundancy.
//
// Default mode analysis; `--write` emits test/fixtures/renderer-citations.js;
// `--check` fails if that fixture is stale.

import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const CMAP_URL = new URL("test/fixtures/compute-map.js", ROOT);
const FIXTURE_URL = new URL("test/fixtures/renderer-citations.js", ROOT);
const write = process.argv.includes("--write");
const check = process.argv.includes("--check");
const CITE_RE = /citationEl\.textContent\s*=\s*("(?:[^"\\]|\\.)*")\s*;/;

function renderFixture(cites) {
  const rows = Object.keys(cites).sort().map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(cites[id])},`).join("\n");
  return `// GENERATED by scripts/extract-citations.mjs. Do not hand-edit.\n// spec-v1185: literal citation strings from bespoke renderers, read by\n// mcp/catalog.mjs as the citation.text for tiles whose citation is not on a\n// render.schema. Regenerate with \`node scripts/extract-citations.mjs --write\`.\nexport const RENDERER_CITATIONS = {\n${rows}\n};\n`;
}

async function main() {
  const { RENDERER_MAP } = await import(new URL("test/fixtures/renderer-map.js", ROOT).href);
  let BESPOKE = {};
  try { ({ BESPOKE_SCHEMAS: BESPOKE } = await import(new URL("test/fixtures/bespoke-schemas.js", ROOT).href)); } catch { BESPOKE = {}; }
  const modCache = new Map();
  const imp = async (rel) => { const u = new URL(rel, CMAP_URL).href; let m = modCache.get(u); if (!m) { m = await import(u); modCache.set(u, m); } return m; };

  const cites = {};
  let scanned = 0;
  for (const id of Object.keys(RENDERER_MAP)) {
    if (BESPOKE[id] && BESPOKE[id].citation) continue; // already exposed via the input schema
    const rreg = RENDERER_MAP[id];
    const rmod = await imp(rreg.module);
    const rf = rmod[rreg.exportName] && rmod[rreg.exportName][id];
    if (!rf || rf.schema) continue; // factory/in-source-schema renderers carry their own citation
    scanned++;
    const m = rf.toString().match(CITE_RE);
    if (m) cites[id] = JSON.parse(m[1]);
  }

  const count = Object.keys(cites).length;
  const fixture = renderFixture(cites);
  if (write) {
    writeFileSync(FIXTURE_URL, fixture);
    console.log(`wrote ${count} renderer citations to test/fixtures/renderer-citations.js`);
  } else if (check) {
    let current = "";
    try { current = readFileSync(FIXTURE_URL, "utf8"); } catch { /* missing */ }
    if (current !== fixture) {
      console.error("✗ renderer-citations.js is stale: a renderer's citation changed but the fixture was not regenerated. Run `node scripts/extract-citations.mjs --write` and commit.");
      process.exit(1);
    }
    console.log(`✓ renderer-citations.js is in sync (${count} citations).`);
  } else {
    console.log(`renderer-citations: ${count} literal citations across ${scanned} bespoke tiles scanned.`);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });

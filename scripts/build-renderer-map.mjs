#!/usr/bin/env node
// Build test/fixtures/renderer-map.js from app.js's TOOL_MODULES declare() table.
//
// spec-v1184: the MCP catalog layer needs to reach each tile's renderer to read
// the field descriptor (`render.schema`) the way it already reaches each tile's
// compute function via compute-map.js. app.js is the single source of truth for
// which module/export holds a tile's renderer -- it registers them with
//
//   declare("./calc-electrical.js", "ELECTRICAL_RENDERERS", ["ohms-law", ...]);
//
// This script parses those calls (text, not import: app.js is a browser module
// that touches the DOM on load and will not import under Node) and emits a
// fixture mapping tile id -> { module, exportName }, the mirror of compute-map.js.
// Module paths are rewritten from app.js's root-relative "./calc-x.js" to the
// "../../calc-x.js" the fixture needs from test/fixtures/, matching compute-map.
//
// Generated file; do not hand-edit. Regenerate with `node scripts/build-renderer-map.mjs`.
// A gate (check-renderer-map.mjs) asserts the checked-in fixture matches a fresh build.

import { readFileSync, writeFileSync } from "node:fs";

const APP_URL = new URL("../app.js", import.meta.url);
const OUT_URL = new URL("../test/fixtures/renderer-map.js", import.meta.url);

// Strip // line comments from a chunk of source without touching string contents.
// The id arrays contain only simple quoted tokens and // comments, no "//" inside
// strings, so a per-line split on an unquoted // is safe here.
function stripLineComments(src) {
  return src
    .split("\n")
    .map((line) => {
      let inStr = null;
      for (let i = 0; i < line.length; i++) {
        const c = line[i];
        if (inStr) {
          if (c === inStr && line[i - 1] !== "\\") inStr = null;
        } else if (c === '"' || c === "'") {
          inStr = c;
        } else if (c === "/" && line[i + 1] === "/") {
          return line.slice(0, i);
        }
      }
      return line;
    })
    .join("\n");
}

export function parseDeclares(appSrc) {
  const src = appSrc;
  const map = {};
  const order = [];
  const seen = new Set();
  const re = /declare\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*\[/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const rawPath = m[1];
    const exportName = m[2];
    // Scan from the "[" that ended the match to its matching "]".
    let depth = 1;
    let i = re.lastIndex;
    for (; i < src.length && depth > 0; i++) {
      if (src[i] === "[") depth++;
      else if (src[i] === "]") depth--;
    }
    const arrBody = stripLineComments(src.slice(re.lastIndex, i - 1));
    const module = rawPath.replace(/^\.\//, "../../");
    for (const idMatch of arrBody.matchAll(/"([^"]+)"/g)) {
      const id = idMatch[1];
      if (seen.has(id)) {
        // A tile id must map to exactly one renderer; a duplicate is a bug in app.js.
        throw new Error(`duplicate tile id in declare() table: ${id}`);
      }
      seen.add(id);
      order.push(id);
      map[id] = { module, exportName };
    }
  }
  return { map, order };
}

function render(map, order) {
  const rows = order
    .map((id) => `  ${JSON.stringify(id)}: { module: ${JSON.stringify(map[id].module)}, exportName: ${JSON.stringify(map[id].exportName)} },`)
    .join("\n");
  return `// Tile id -> { module: relative path, exportName: renderer registry export }.
//
// GENERATED by scripts/build-renderer-map.mjs from app.js's declare() table.
// Do not hand-edit; run \`node scripts/build-renderer-map.mjs\` to regenerate.
//
// spec-v1184: the mirror of compute-map.js for the renderer side. mcp/catalog.mjs
// imports the module, reads mod[exportName][id], and pulls the retained
// \`render.schema\` (field descriptor) from it. Module paths are relative to THIS
// file (test/fixtures/), the same convention compute-map.js uses.
export const RENDERER_MAP = {
${rows}
};
`;
}

function main() {
  const appSrc = readFileSync(APP_URL, "utf8");
  const { map, order } = parseDeclares(appSrc);
  writeFileSync(OUT_URL, render(map, order));
  process.stderr.write(`[build-renderer-map] wrote ${order.length} tile renderer mappings\n`);
}

// Run when invoked directly; export parseDeclares for the gate to reuse.
if (import.meta.url === `file://${process.argv[1]}`) main();

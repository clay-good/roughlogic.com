#!/usr/bin/env node
// Build test/fixtures/renderer-map.js from tool-modules.js's TOOL_MODULES table.
//
// spec-v1184: the MCP catalog layer needs to reach each tile's renderer to read
// the field descriptor (`render.schema`) the way it already reaches each tile's
// compute function via compute-map.js. tool-modules.js is the single source of truth for
// which module/export holds a tile's renderer -- it registers them with
//
//   declare("./calc-electrical.js", "ELECTRICAL_RENDERERS", ["ohms-law", ...]);
//
// This script parses those calls (text, not import: tool-modules.js is a browser module
// that touches the DOM on load and will not import under Node) and emits a
// fixture mapping tile id -> { module, exportName }, the mirror of compute-map.js.
// Module paths are rewritten from tool-modules.js's root-relative "./calc-x.js" to the
// "../../calc-x.js" the fixture needs from test/fixtures/, matching compute-map.
//
// Generated file; do not hand-edit. Regenerate with `node scripts/build-renderer-map.mjs`.
// A gate (check-renderer-map.mjs) asserts the checked-in fixture matches a fresh build.

import { readFileSync, writeFileSync } from "node:fs";

const MODULES_URL = new URL("../tool-modules.js", import.meta.url);
const OUT_URL = new URL("../test/fixtures/renderer-map.js", import.meta.url);

// Strip // line comments from a chunk of source without touching string contents.
// The id arrays contain only simple quoted tokens and // comments, no "//" inside
// strings, so a per-line split on an unquoted // is safe here.
function stripLineComments(src) {
  return src
    .split("\n")
    .map((line) => {
      let inStr = null;
      for (let i = 0; i < line.length; i++) {
        const c = line[i];
        if (inStr) {
          if (c === inStr && line[i - 1] !== "\\") inStr = null;
        } else if (c === '"' || c === "'") {
          inStr = c;
        } else if (c === "/" && line[i + 1] === "/") {
          return line.slice(0, i);
        }
      }
      return line;
    })
    .join("\n");
}

export function parseDeclares(modulesSrc) {
  const src = modulesSrc;
  const map = {};
  const order = [];
  const seen = new Set();
  const re = /declare\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*\[/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const rawPath = m[1];
    const exportName = m[2];
    // Scan from the "[" that ended the match to its matching "]".
    let depth = 1;
    let i = re.lastIndex;
    for (; i < src.length && depth > 0; i++) {
      if (src[i] === "[") depth++;
      else if (src[i] === "]") depth--;
    }
    const arrBody = stripLineComments(src.slice(re.lastIndex, i - 1));
    const module = rawPath.replace(/^\.\//, "../../");
    for (const idMatch of arrBody.matchAll(/"([^"]+)"/g)) {
      const id = idMatch[1];
      if (seen.has(id)) {
        // A tile id must map to exactly one renderer; a duplicate is a bug in
        // tool-modules.js (its `declare` helper assigns, so the LAST one would win).
        throw new Error(`duplicate tile id in declare() table: ${id}`);
      }
      seen.add(id);
      order.push(id);
      map[id] = { module, exportName };
    }
  }
  return { map, order };
}

function render(map, order) {
  const rows = order
    .map((id) => `  ${JSON.stringify(id)}: { module: ${JSON.stringify(map[id].module)}, exportName: ${JSON.stringify(map[id].exportName)} },`)
    .join("\n");
  return `// Tile id -> { module: relative path, exportName: renderer registry export }.
//
// GENERATED by scripts/build-renderer-map.mjs from tool-modules.js's declare()
// table. (This line said "app.js" until 2026-11-26, from before spec-v10 H.1
// moved the table into its own lazily-loaded shard.)
// Do not hand-edit; run \`node scripts/build-renderer-map.mjs\` to regenerate.
//
// spec-v1184: the mirror of compute-map.js for the renderer side. mcp/catalog.mjs
// imports the module, reads mod[exportName][id], and pulls the retained
// \`render.schema\` (field descriptor) from it. Module paths are relative to THIS
// file (test/fixtures/), the same convention compute-map.js uses.
export const RENDERER_MAP = {
${rows}
};
`;
}

function main() {
  const modulesSrc = readFileSync(MODULES_URL, "utf8");
  const { map, order } = parseDeclares(modulesSrc);
  const body = render(map, order);

  // --check: this generator had no staleness gate until 2026-11-26, and it was
  // the only one of the seven generated fixtures without one. The file it
  // writes is what every sweep and test iterating RENDERER_MAP reads, so a tile
  // added to tool-modules.js and not regenerated here would be SILENTLY SKIPPED
  // by all of them -- they would stay green while covering one tile fewer. The
  // committed copy was already out of step when this was added: same 2,288
  // entries and the same values, in a different order.
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT_URL, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== body) {
      process.stderr.write("build-renderer-map FAILED: test/fixtures/renderer-map.js is stale. Run `node scripts/build-renderer-map.mjs` and commit.\n");
      process.exit(1);
    }
    process.stdout.write(`build-renderer-map OK: ${order.length} tile renderer mappings match tool-modules.js.\n`);
    return;
  }

  writeFileSync(OUT_URL, body);
  process.stderr.write(`[build-renderer-map] wrote ${order.length} tile renderer mappings\n`);
}

// Run when invoked directly; export parseDeclares for the gate to reuse.
if (import.meta.url === `file://${process.argv[1]}`) main();
